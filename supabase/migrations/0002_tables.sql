-- ── 1. roles ────────────────────────────────────────────────
CREATE TABLE roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  rol tipo_rol,
  CONSTRAINT roles_pkey PRIMARY KEY (id)
);

-- ── 2. usuario ──────────────────────────────────────────────
CREATE TABLE usuario (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  clerk_user_id VARCHAR NOT NULL,
  firebase_user_id VARCHAR,
  nombre_completo VARCHAR NOT NULL,
  email VARCHAR NOT NULL,
  telefono VARCHAR,
  avatar_url TEXT,
  fecha_registro TIMESTAMPTZ NOT NULL DEFAULT now(),
  ultimo_login TIMESTAMPTZ,
  perfil_publico BOOLEAN NOT NULL DEFAULT true,
  estado_usuario estado_usuario DEFAULT 'activo',
  roles_id BIGINT,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now(),
  CONSTRAINT usuario_pkey PRIMARY KEY (id),
  CONSTRAINT usuario_clerk_user_id_key UNIQUE (clerk_user_id),
  CONSTRAINT usuario_email_key UNIQUE (email),
  CONSTRAINT usuario_firebase_user_id_key UNIQUE (firebase_user_id),
  CONSTRAINT usuario_roles_id_fkey FOREIGN KEY (roles_id) REFERENCES roles(id)
);

-- ── 3. organizacion ─────────────────────────────────────────
CREATE TABLE organizacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  anfitrion_id BIGINT NOT NULL,
  nombre VARCHAR,
  descripcion TEXT,
  email_anfitrion VARCHAR NOT NULL,
  tipo tipo_organizacion NOT NULL,
  logo_url TEXT,
  CONSTRAINT organizacion_pkey PRIMARY KEY (id),
  CONSTRAINT organizacion_anfitrion_id_fkey FOREIGN KEY (anfitrion_id) REFERENCES usuario(id)
);

-- ── 4. categoria ────────────────────────────────────────────
CREATE TABLE categoria (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  nombre VARCHAR NOT NULL,
  descripcion TEXT,
  activa BOOLEAN NOT NULL DEFAULT true,
  CONSTRAINT categoria_pkey PRIMARY KEY (id)
);

-- ── 5. plazoleta ────────────────────────────────────────────
CREATE TABLE plazoleta (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  nombre VARCHAR NOT NULL,
  descripcion TEXT,
  tipo_ubicacion tipo_ubicacion NOT NULL,
  slug VARCHAR(50) NOT NULL,
  categoria_principal_id BIGINT,
  CONSTRAINT plazoleta_pkey PRIMARY KEY (id),
  CONSTRAINT plazoleta_slug_unique UNIQUE (slug),
  CONSTRAINT plazoleta_categoria_principal_id_fkey
    FOREIGN KEY (categoria_principal_id) REFERENCES categoria(id)
);

-- ── 6. tienda ───────────────────────────────────────────────
CREATE TABLE tienda (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  id_propietario BIGINT NOT NULL,
  nombre_tienda VARCHAR NOT NULL,
  descripcion TEXT,
  logo_url TEXT,
  redes_sociales JSONB,
  organizacion_id BIGINT,
  email_contacto VARCHAR(255),
  telefono_contacto VARCHAR(50),
  direccion TEXT,
  total_visitas INTEGER DEFAULT 0,
  total_contactos_whatsapp INTEGER DEFAULT 0,
  fecha_ultima_visita TIMESTAMP,
  CONSTRAINT tienda_pkey PRIMARY KEY (id),
  CONSTRAINT tienda_nombre_tienda_key UNIQUE (nombre_tienda),
  CONSTRAINT tienda_id_propietario_unique UNIQUE (id_propietario),
  CONSTRAINT tienda_id_propietario_fkey FOREIGN KEY (id_propietario) REFERENCES usuario(id),
  CONSTRAINT tienda_organizacion_id_fkey FOREIGN KEY (organizacion_id) REFERENCES organizacion(id)
);

-- ── 7. producto ─────────────────────────────────────────────
CREATE TABLE producto (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_actualizacion TIMESTAMPTZ,
  tienda_id BIGINT NOT NULL,
  categoria_id BIGINT NOT NULL,
  nombre VARCHAR NOT NULL,
  descripcion TEXT,
  precio_base NUMERIC NOT NULL,
  cantidad SMALLINT NOT NULL,
  calificacion_promedio NUMERIC,
  total_valoracion SMALLINT,
  estado_producto estado_producto DEFAULT 'activo',
  total_visualizaciones INTEGER NOT NULL DEFAULT 0,
  total_clicks_whatsapp INTEGER DEFAULT 0,
  total_compartidos INTEGER DEFAULT 0,
  total_clicks_instagram INTEGER DEFAULT 0,
  total_clicks_facebook INTEGER DEFAULT 0,
  fecha_ultima_interaccion TIMESTAMP,
  CONSTRAINT producto_pkey PRIMARY KEY (id),
  CONSTRAINT producto_id_key UNIQUE (id),
  CONSTRAINT producto_tienda_id_fkey FOREIGN KEY (tienda_id) REFERENCES tienda(id),
  CONSTRAINT producto_categoria_id_fkey FOREIGN KEY (categoria_id) REFERENCES categoria(id)
);

-- ── 8. horario ──────────────────────────────────────────────
CREATE TABLE horario (
