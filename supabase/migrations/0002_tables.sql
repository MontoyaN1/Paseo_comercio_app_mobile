-- ── 10. miembros_organizacion ───────────────────────────────
CREATE TABLE miembros_organizacion (
  id BIGSERIAL NOT NULL,
  organizacion_id BIGINT NOT NULL,
  usuario_id BIGINT NOT NULL,
  email VARCHAR(255) NOT NULL,
  nombre VARCHAR(255) NOT NULL,
  rol_id INTEGER NOT NULL,
  estado VARCHAR(50) DEFAULT 'Pendiente',
  fecha_invitacion TIMESTAMPTZ DEFAULT now(),
  fecha_aceptacion TIMESTAMPTZ,
  fecha_rechazo TIMESTAMPTZ,
  invitado_por BIGINT,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now(),
  CONSTRAINT miembros_organizacion_pkey PRIMARY KEY (id),
  CONSTRAINT unique_usuario_organizacion UNIQUE (organizacion_id, usuario_id),
  CONSTRAINT fk_miembro_organizacion FOREIGN KEY (organizacion_id) REFERENCES organizacion(id),
  CONSTRAINT fk_miembro_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id),
  CONSTRAINT fk_miembro_invitado_por FOREIGN KEY (invitado_por) REFERENCES usuario(id),
  CONSTRAINT check_estado_valido CHECK (estado IN ('Pendiente', 'Activo', 'Rechazado'))
);

-- ── 11. notificacion ────────────────────────────────────────
CREATE TABLE notificacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  remitente_id BIGINT NOT NULL,
  destinatario_id BIGINT NOT NULL,
  asunto VARCHAR,
  mensaje TEXT,
  tipo VARCHAR(50) DEFAULT 'mensaje_sistema',
  leida BOOLEAN DEFAULT false,
  fecha_leida TIMESTAMPTZ,
  accion_url VARCHAR(500),
  metadata JSONB,
  referencia_id BIGINT,
  referencia_tipo VARCHAR(50),
  CONSTRAINT notificacion_pkey PRIMARY KEY (id),
  CONSTRAINT notificacion_remitente_id_fkey FOREIGN KEY (remitente_id) REFERENCES usuario(id),
  CONSTRAINT notificacion_destinatario_id_fkey FOREIGN KEY (destinatario_id) REFERENCES usuario(id),
  CONSTRAINT notificacion_tipo_check CHECK (
    tipo IN (
      'invitacion_organizacion', 'aceptacion_invitacion', 'rechazo_invitacion',
      'organizacion_eliminada', 'miembro_expulsado', 'miembro_abandono',
      'mensaje_sistema', 'alerta'
    )
  )
);

